type Flag = "featured" | "bestseller" | "new" | "quote";

interface Seed {
  sku: string;
  name: string;
  brand: string;
  cat: string;
  sub: string;
  icon: string;
  price: number | null;
  prev?: number;
  stock?: number;
  short: string;
  desc: string;
  specs: [string, string][];
  features: string[];
  flags?: Flag[];
  kind?: ProductKind;
  unit?: string;
  /** Días atrás en que se dio de alta el producto (ordena "más recientes"). */
  age?: number;
}

const slugify = (value: string): string =>
  value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

function availabilityOf(stock: number, quoteOnly: boolean): ProductAvailability {
  if (quoteOnly) return "on_request";
  if (stock <= 0) return "out_of_stock";
  if (stock <= 8) return "low_stock";
  return "in_stock";
}

function build(seed: Seed): Product {
  const flags = seed.flags ?? [];
  const quoteOnly = flags.includes("quote");
  const stock = seed.stock ?? 24;
  const age = seed.age ?? 120;
  const createdAt = new Date(Date.UTC(2026, 7, 19) - age * 86400000).toISOString();

  return {
    id: seed.sku.toLowerCase(),
    slug: slugify(`${seed.name}`),
    sku: seed.sku,
    name: seed.name,
    shortDescription: seed.short,
    description: seed.desc,
    category: seed.cat,
    subcategory: seed.sub,
    brand: seed.brand,
    price: quoteOnly ? null : seed.price,
    previousPrice: seed.prev ?? null,
    stock,
    availability: availabilityOf(stock, quoteOnly),
    images: [1, 2, 3].map((n) => `/img/products/${seed.icon}-${n}.svg`),
    specifications: seed.specs.map(([label, value]) => ({ label, value })),
    features: seed.features,
    kind: seed.kind ?? "retail",
    featured: flags.includes("featured"),
    bestseller: flags.includes("bestseller"),
    isNew: flags.includes("new"),
    sale: Boolean(seed.prev),
    quoteOnly,
    unit: seed.unit,
    createdAt,
  };
}

